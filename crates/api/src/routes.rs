/// Router file.
///
/// This file regroups all the available routes from the API and organizes them.
/// Also adds the middleware layer and defines private routes such as Prometheus /metrics.
///
/// To add a new route, define it using utoipa decorator and specify:
/// - its documentation
/// - its method
/// - its path
/// - its responses examples
///
/// For example:
///
/// ```rs
/// /// Health Check of the API
/// #[utoipa::path(
///     get,
///     path = "/",
///     responses(
///         (status = OK, description = "The API is up and running."),
///     ),
/// )]
/// pub(crate) async fn health_check() -> &'static str {
///     ""
/// }
/// ```
///
/// Then import it as follows, with its `__path_` that is generated by utoipa:
///
/// ```rs
/// use crate::misc::{health_check, __path_health_check};
/// ```
///
/// Finally, add the route to the OpenApiRouter:
///
/// ```rs
/// .routes(routes!(health_check))
/// ```
use crate::{
    app_state::AppState,
    endpoints::{
        api_key::endpoints::{
            __path_create_api_key, __path_delete_api_key, __path_get_api_key,
            create_api_key, delete_api_key, get_api_key,
        },
        auth::endpoints::{
            __path_callback, __path_get_me, __path_login, __path_logout, __path_refresh_token,
            callback, get_me, login, logout, refresh_token,
        },
        ping::endpoints::{__path_ping, ping},
        storage::endpoints::{
            __path_delete_stored_file, __path_download, __path_upload,
            delete_stored_file, download, upload,
        },
        user::endpoints::{__path_get_user, get_user},
    },
};
use axum::{Router, routing::get};

use axum::http::StatusCode;
use axum::http::header::{AUTHORIZATION, CONTENT_TYPE};
use axum::http::Method;
use axum_prometheus::metrics_exporter_prometheus::PrometheusHandle;
use config::Config;
use std::future::ready;
use std::iter::once;
use std::time::Duration;
use tower::ServiceBuilder;
use tower_http::{
    CompressionLevel,
    compression::CompressionLayer,
    cors::CorsLayer,
    decompression::RequestDecompressionLayer,
    normalize_path::NormalizePathLayer,
    sensitive_headers::{
        SetSensitiveRequestHeadersLayer, SetSensitiveResponseHeadersLayer,
    },
    timeout::TimeoutLayer,
    trace::TraceLayer,
};
use utoipa::openapi::{InfoBuilder, OpenApi};
use utoipa_axum::{router::OpenApiRouter, routes};
