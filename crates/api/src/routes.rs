/// Router file.
///
/// This file regroups all the available routes from the API and organizes them.
/// Also adds the middleware layer and defines private routes such as Prometheus /metrics.
///
/// To add a new route, define it using utoipa decorator and specify:
/// - its documentation
/// - its method
/// - its path
/// - its responses examples
///
/// For example:
///
/// ```rs
/// /// Health Check of the API
/// #[utoipa::path(
///     get,
///     path = "/",
///     responses(
///         (status = OK, description = "The API is up and running."),
///     ),
/// )]
/// pub(crate) async fn health_check() -> &'static str {
///     ""
/// }
/// ```
///
/// Then import it as follows, with its `__path_` that is generated by utoipa:
///
/// ```rs
/// use crate::misc::{health_check, __path_health_check};
/// ```
///
/// Finally, add the route to the OpenApiRouter:
///
/// ```rs
/// .routes(routes!(health_check))
/// ```
use crate::{
    app_state::AppState,
    endpoints::{
        api_key::endpoints::{
            __path_create_api_key, __path_delete_api_key, __path_get_api_key,
            create_api_key, delete_api_key, get_api_key, tag as api_key_tag,
        },
        auth::endpoints::{
            __path_callback, __path_login, __path_logout, __path_me, __path_refresh,
            __path_register, callback, login, logout, me, refresh, register,
            tag as auth_tag,
        },
        ping::endpoints::{__path_ping, ping, tag as ping_tag},
        storage::endpoints::{
            __path_delete_stored_file, __path_download, __path_upload,
            delete_stored_file, download, tag as storage_tag, upload,
        },
        user::endpoints::{__path_get_user, get_user, tag as user_tag},
    },
    middlewares::rate_limiter::rate_limiter_layer,
    observability::{MakeRequestUuidV7, make_request_span},
};
