/// Builds the [`OpenApiRouter`] holding every public API route.
///
/// This only assembles the route definitions and their generated schemas, so it
/// can be called without any running service (database, cache, storage, ...).
/// It is the single source of truth shared by [`public_routes`] and [`openapi`].
fn api_router() -> OpenApiRouter<AppState> {
    OpenApiRouter::<AppState>::new()
        .routes(routes!(ping))
        .routes(routes!(get_user))
        // Object storage
        .routes(routes!(upload))
        .routes(routes!(download))
        .routes(routes!(delete_stored_file))
        // API Key
        .routes(routes!(create_api_key))
        .routes(routes!(get_api_key))
        .routes(routes!(delete_api_key))
        // Authentication
        .routes(routes!(login))
        .routes(routes!(register))
        .routes(routes!(callback))
        .routes(routes!(refresh))
        .routes(routes!(logout))
        .routes(routes!(me))
}

/// Metadata advertised in the generated OpenAPI document.
fn api_info() -> utoipa::openapi::Info {
    InfoBuilder::new()
        .title(env!("CARGO_PKG_NAME"))
        .description(option_env!("CARGO_PKG_DESCRIPTION"))
        .version(env!("CARGO_PKG_VERSION"))
        .build()
}

/// Builds the OpenAPI document describing the public API.
///
/// Requires no running service, so it can be serialized offline (e.g. to
/// generate the frontend API types).
pub fn openapi() -> OpenApi {
    let server = Server::new("/api");
    let (_, mut openapi) = api_router().split_for_parts();
    openapi.info = api_info();
    openapi.tags = Some(api_tags());
    openapi.servers = Some(vec![server]);
    openapi
}

/// Swagger categories, in display order. Each entry's name and description live
/// next to the endpoints it groups (see `endpoints::macros::declare_tag`).
fn api_tags() -> Vec<utoipa::openapi::Tag> {
    vec![
        auth_tag(),
        user_tag(),
        storage_tag(),
        api_key_tag(),
        ping_tag(),
    ]
}

/// Public routes that qre exposed to the world
pub fn public_routes(config: &Config, state: AppState) -> Router {
    let (api_routes, _) = api_router().split_for_parts();
    // The whole API (typed endpoints + auth BFF) lives under `/api`, matching the
    // frontend's `VITE_APP_API_URL`. Swagger keeps its own absolute path at the root.
    let routes = Router::new()
        .nest("/api", api_routes)
        .merge(swagger(config, openapi()));

    with_middlewares(routes, config).with_state(state)
}

/// Wraps `routes` in the production middleware stack.
///
/// Extracted from [`public_routes`] so the exact layer ordering can be exercised
/// by tests without standing up an [`AppState`]: a test that hand-rolls its own
/// stack proves nothing about the one that ships.
pub(crate) fn with_middlewares<S>(routes: Router<S>, config: &Config) -> Router<S>
where
    S: Clone + Send + Sync + 'static,
{
    // `ServiceBuilder` wraps outside-in: the first layer declared here is the
    // outermost one, so a request traverses them top to bottom and the response
    // travels back up bottom to top. Order is load-bearing below.
    let middleware = ServiceBuilder::new()
        // Outermost, so no later layer can log the request's Authorization header
        .layer(SetSensitiveRequestHeadersLayer::new(once(AUTHORIZATION)))
        // Reuse an inbound x-request-id or mint a fresh UUID v7. Must wrap the trace
        // layer so the span can read the id from the request headers.
        .layer(SetRequestIdLayer::x_request_id(MakeRequestUuidV7))
        // Echo the request id back to the client in the response headers
        .layer(PropagateRequestIdLayer::x_request_id())
        // Scope every event of the request under a span carrying the request_id
        .layer(TraceLayer::new_for_http().make_span_with(make_request_span))
        // Inside the trace layer, so responses are scrubbed before it sees them
        .layer(SetSensitiveResponseHeadersLayer::new(once(AUTHORIZATION)))
        // Reflect the frontend origin and allow credentials so the browser sends and
        // accepts the httpOnly auth cookies (a wildcard origin is rejected with creds).
        // Wraps the rate limiter so even a 429 carries the CORS headers the browser
        // needs to read it.
        .layer(cors_layer(config))
        .layer(NormalizePathLayer::trim_trailing_slash())
        // Bounds everything below it, decompression included
        .layer(TimeoutLayer::with_status_code(
            StatusCode::REQUEST_TIMEOUT,
            Duration::from_secs(config.api.timeout_sec.into()),
        ))
        .layer(RequestDecompressionLayer::new())
        .layer(CompressionLayer::new().quality(CompressionLevel::Best))
        // Innermost: the governor layer only accepts a service answering a plain
        // `axum::response::Response`, which the compression layers above rewrap.
        // It still rejects abusive callers before the router picks a handler, and
        // its 429 travels back out through the CORS and tracing layers.
        .layer(rate_limiter_layer(config));

    routes.layer(middleware)
}

/// CORS layer reflecting the configured frontend origin and allowing credentials,
/// which is required for the browser to send/accept the httpOnly auth cookies.
fn cors_layer(config: &Config) -> CorsLayer {
    let origin = config
        .oidc
        .frontend_url
        .trim_end_matches('/')
        .parse::<axum::http::HeaderValue>();

    let mut cors = CorsLayer::new()
        .allow_methods(AllowMethods::mirror_request())
        .allow_headers(AllowHeaders::mirror_request())
        .allow_credentials(true);

    cors = match origin {
        Ok(origin) => cors.allow_origin(origin),
        Err(_) => cors.allow_origin(AllowOrigin::mirror_request()),
    };

    cors
}

/// Swagger UI and OpenAPI routes layer.
fn swagger(config: &Config, openapi: OpenApi) -> SwaggerUi {
    let swagger_config = config.swagger.as_ref().unwrap().clone();
    let swagger_ui_path = swagger_config.swagger_ui_path;
    let openapi_path = swagger_config.openapi_path;
    let mut openapi = openapi;
    openapi.info = api_info();
    SwaggerUi::new(swagger_ui_path).url(openapi_path, openapi)
}

/// Metrics routes that are exposed to Prometheus
pub fn try_metrics_routes(
    path: &str,
    metric_handle: PrometheusHandle,
) -> Result<Router, anyhow::Error> {
    Ok(Router::new().route(path, get(move || ready(metric_handle.render()))))
}
